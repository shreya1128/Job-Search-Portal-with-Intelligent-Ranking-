"""Scratch launcher for the logged-in pages (Saved Jobs, Profile, workspace, account) for visual checks.

It never touches the real tables.  It fills a SEPARATE scratch database (name must contain "test"; every table in it is dropped first) with a handful of REAL postings copied from the real
database, creates one demo account through the real registration and profile code, saves some of the postings, and serves the site on top of that scratch database.
The demo account (user name "demo", password printed below) and its saved jobs, searches and profile are made up for the screenshots: they are not real user data.

    python tools/phase7_scratch/serve_stage2.py 5058
Needs the MariaDB / MySQL server of the sandbox (tools/sandbox/startdb.sh) and a database called jobintel_webtest that the jobintel user may write to."""
import datetime as dt
import sys

from sqlalchemy import create_engine, text
from sqlalchemy.orm import Session

from jobintel.db import models as M
from jobintel.db.models import Base
from jobintel.db.session import get_engine
from jobintel.web import create_app
from jobintel.web.backend import Backend
from jobintel.web.settings import WebSettings

PORT = int(sys.argv[1]) if len(sys.argv) > 1 else 5058
SCRATCH_URL = "mysql+pymysql://jobintel:testpw@127.0.0.1:3307/jobintel_webtest"
DEMO_USER, DEMO_PASSWORD = "demo", "demo password 42"

real, scratch = get_engine(), create_engine(SCRATCH_URL)
assert "test" in scratch.url.database
Base.metadata.drop_all(scratch)
Base.metadata.create_all(scratch)

PICK = [  # (label, SQL returning job ids)
    ("data and AI jobs with a company, city and stated experience",
     "select j.job_id from jobs j join companies c on c.company_id=j.company_id where j.duplicate_of is null and j.is_fraudulent=0 and c.name_is_derived=0 and j.cluster='data_ai' "
     "and j.city is not null and j.experience_text is not null order by j.job_id limit 6"),
    ("a posting whose employer name was generated by the loader", "select j.job_id from jobs j join companies c on c.company_id=j.company_id where c.name_is_derived=1 and j.duplicate_of is null limit 1"),
    ("the longest title", "select job_id from jobs where duplicate_of is null and is_fraudulent=0 order by char_length(title) desc limit 1"),
    ("a flagged posting", "select job_id from jobs where is_fraudulent=1 and duplicate_of is null limit 1"),
    ("postings without stated experience", "select job_id from jobs where duplicate_of is null and is_fraudulent=0 and experience_min is null and company_id is not null limit 3"),
    ("postings with an application link", "select job_id from jobs where duplicate_of is null and is_fraudulent=0 and url is not null and company_id is not null limit 2"),
]
with real.connect() as c:
    ids = []
    for label, sql in PICK:
        got = [int(r[0]) for r in c.execute(text(sql))]
        print(f"{label}: {got}")
        ids += [i for i in got if i not in ids]
idlist = ",".join(str(i) for i in ids)


def cols(table):
    return ", ".join(f"`{c.name}`" for c in Base.metadata.tables[table].columns)


def copy(table, where=""):
    with scratch.begin() as c:
        c.execute(text(f"INSERT INTO jobintel_webtest.`{table}` ({cols(table)}) SELECT {cols(table)} FROM jobintel.`{table}` {where}"))


copy("crawler_sources")
copy("companies", f"WHERE company_id IN (SELECT company_id FROM jobintel.jobs WHERE job_id IN ({idlist}))")
copy("jobs", f"WHERE job_id IN ({idlist})")
copy("skills")
copy("job_skills", f"WHERE job_id IN ({idlist})")
print("copied", len(ids), "real postings into the scratch database")

st = WebSettings.from_env(warmup=False, log_searches=False, secret_key="visual-check-only")
app = create_app(st, Backend(st, db=scratch))
be = app.extensions["jobintel"].backend
be.warm_up(("index", "engine"))

# the demo account, through the real code paths
c = app.test_client()


def tok():
    c.get("/about")
    with c.session_transaction() as s:
        return s["_csrf"]


c.post("/register", data={"csrf_token": tok(), "username": DEMO_USER, "email": "demo@example.com", "password": DEMO_PASSWORD, "confirm": DEMO_PASSWORD})
c.post("/profile", data={"csrf_token": tok(), "full_name": "Demo Person", "education": "B.Sc. Statistics", "role": "data analyst", "location": "Pune", "years": "2",
                         "summary": "Made-up demo account used for screenshots.", "skills": "sql, python, excel, tableau"})
for j in ids[:6] + ids[6:8]:
    c.post("/api/interact", json={"job_id": j, "action": "save"}, headers={"X-CSRF-Token": tok()})
c.post(f"/saved/{ids[1]}/applied", data={"csrf_token": tok(), "value": "1"})
c.post(f"/saved/{ids[3]}/applied", data={"csrf_token": tok(), "value": "1"})
for j in ids[8:11]:
    c.get(f"/job/{j}")
with Session(scratch) as s:
    uid = s.query(M.User.user_id).filter_by(username=DEMO_USER).scalar()
    now = dt.datetime.now()
    for k, q in enumerate(["data analyst pune", "python sql", "entry level machine learning jobs"]):
        s.add(M.Search(user_id=uid, query_text=q, n_results=40 - 7 * k, ranking_model="hybrid", created_at=now - dt.timedelta(hours=k + 1)))
    s.commit()
print(f"demo account ready: user name {DEMO_USER!r}, password {DEMO_PASSWORD!r}")
app.run(host="127.0.0.1", port=PORT, threaded=True, use_reloader=False)
