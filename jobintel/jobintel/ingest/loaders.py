# =========================================================================== NAUKRI
def load_naukri(path: Path, limit: Optional[int] = None) -> Iterator[JobRecord]:
    df = pd.read_csv(path)
    for i, r in enumerate(df.itertuples(index=False)):
        if limit and i >= limit:
            break
        role, comp, loc, exp, skills = r[0], r[1], r[2], r[3], r[4]   # Job_Role, Company, Location, Job Experience, Skills/Description
        cities, country = C.parse_naukri_location(_s(loc) or "")
        lo, hi = C.parse_exp_range(_s(exp))
        tags = [t.strip() for t in str(skills or "").split(",") if t.strip()]
        yield JobRecord(
            source="naukri", external_id=f"naukri-{i}", title=_s(role) or "Unknown role", company=_s(comp),
            location_raw=_s(loc), city=cities[0] if cities else None, cities=cities, country=country or "India",
            description=None, skills=tags, experience_min=lo, experience_max=hi, experience_text=_s(exp) and f"{_s(exp)} years",
            experience_source="dataset" if lo is not None else None, text_quality="skills_only")


# =========================================================================== EMSCAD (fake_job_postings.csv)
def load_emscad(path: Path, limit: Optional[int] = None) -> Iterator[JobRecord]:
    df = pd.read_csv(path)
    for i, r in enumerate(df.to_dict("records")):
        if limit and i >= limit:
            break
        desc, req, ben = _s(r.get("description")), _s(r.get("requirements")), _s(r.get("benefits"))
        parts = [desc or ""]
        if req:
            parts.append("Requirements:\n" + req)
        if ben:
            parts.append("Benefits:\n" + ben)
        text = "\n\n".join(p for p in parts if p).strip()
        profile = _s(r.get("company_profile"))
        company = f"Company-{hashlib.sha1(profile.lower().encode()).hexdigest()[:6]}" if profile else None
        country, region, city = C.parse_emscad_location(_s(r.get("location")) or "")
        slo, shi = C.parse_numeric_range(_s(r.get("salary_range")))
        sen = _s(r.get("required_experience"))
        edu = _s(r.get("required_education"))
        lo, hi = C.seniority_to_exp(sen)
        yield JobRecord(
            source="emscad", external_id=str(r.get("job_id", i)), title=_s(r.get("title")) or "Unknown role", company=company,
            company_profile=profile, company_name_is_derived=True, location_raw=_s(r.get("location")), city=city,
            cities=[city] if city else [], region=region, country=country, description=text or None,
            salary_min=slo, salary_max=shi, employment_type=_s(r.get("employment_type")), seniority=sen,
            education=None if edu in (None, "Unspecified") else edu, category=_s(r.get("function")), industry=_s(r.get("industry")),
            experience_min=lo, experience_max=hi, experience_source="seniority_map" if lo is not None else None,
            is_fraudulent=bool(int(r.get("fraudulent", 0) or 0)), text_quality="full" if text and len(text.split()) >= 20 else "none",
            extras={"department": _s(r.get("department")), "telecommuting": r.get("telecommuting")})


# =========================================================================== MyCareersFuture (JSON)
def _mcf_categories(lst) -> List[str]:
    """The source split 'Admin / Secretarial' at '/' into list items; re-join then split on ','."""
    if not isinstance(lst, list):
        return []
    joined = "/".join(lst)
    return [re.sub(r"\s*/\s*", " / ", c).strip() for c in joined.split(",") if c.strip()]


def load_mcf(path: Path, limit: Optional[int] = None) -> Iterator[JobRecord]:
    jobs = json.loads(Path(path).read_text(encoding="utf-8"))["jobs"]
    from collections import Counter
    id_count = Counter(str(j.get("job_id")) for j in jobs)      # the source job_id is NOT unique (e.g. '5-Recruiter')
    for i, r in enumerate(jobs):
        if limit and i >= limit:
            break
        sid = str(r.get("job_id", i))
        ext_id = sid if id_count[sid] == 1 else f"{sid}#{i}"
        cats = _mcf_categories(r.get("job_category"))
        text = "\n\n".join(x for x in (_s(r.get("requirements_and_role")), _s(r.get("job_requirements"))) if x)
        lo, hi = C.parse_exp_range(_s(r.get("min_experience")))
        sal = C.parse_salary_text(_s(r.get("salary")), "SGD")
        skills = [s.strip() for s in (r.get("skills_required") or []) if str(s).strip()]
        yield JobRecord(
            source="mcf", external_id=ext_id, title=re.split(r"\s*\[", _s(r.get("job_title")) or "")[0].strip() or "Unknown role",
            company=_s(r.get("company_name")), company_profile=_s(r.get("company_info")), location_raw=_s(r.get("location")),
            city="Singapore", cities=["Singapore"], country="Singapore", description=text or None, skills=skills,
            experience_min=lo, experience_max=hi, experience_text=_s(r.get("min_experience")),
            experience_source="dataset" if lo is not None else None,
            salary_min=sal.get("min"), salary_max=sal.get("max"), salary_currency=sal.get("currency"), salary_period=sal.get("period"),
            employment_type=_s(r.get("employment_type")), seniority=_s(r.get("seniority")), category=cats[0] if cats else None,
            posting_date=C.to_date(r.get("posting_date")), text_quality="preprocessed" if text else "skills_only",
            extras={"all_categories": cats, "no_of_applications": r.get("no_of_applications")})


# =========================================================================== LinkedIn sample (meta CSV, optionally + job_summary)
_EDU_TAG = re.compile(r"\b(bachelor|master|degree|diploma|ph\.?d|doctorate|high school|ged|associate'?s?|college|undergraduate|graduate)\b", re.I)
_CERT_TAG = re.compile(r"\b(certif\w*|licen[sc]\w*|cpr|bls|acls|pals|cdl|pmp|cpa|cissp|ccna|clearance)\b", re.I)
_EXP_TAG = re.compile(r"(\d+\+?\s*(?:years?|yrs?)|\bexperience (?:in|with|as)\b)", re.I)


def classify_linkedin_tag(tag: str) -> str:
    """skill | education | certification | experience | noise  (the dataset's skill lists mix all of these)."""
    t = tag.strip()
    if not t or len(t) > 70 or re.search(r"code:|\d{4,}", t):
        return "noise"
    if _CERT_TAG.search(t):
        return "certification"
    if _EDU_TAG.search(t):
        return "education"
    if _EXP_TAG.search(t):
        return "experience"
    return "skill"


def _ext_id(link: str) -> str:
    return link if len(link) <= 250 else hashlib.sha1(link.encode()).hexdigest()


def load_linkedin(path: Path, limit: Optional[int] = None) -> Iterator[JobRecord]:
    df = pd.read_csv(path, dtype=str)
    has_text = "job_summary" in df.columns
    for i, r in enumerate(df.to_dict("records")):
        if limit and i >= limit:
            break
        city, region = C.parse_us_style_location(_s(r.get("job_location")) or "")
        tags = [t.strip() for t in str(r.get("job_skills") or "").split(",") if t.strip()]
        kinds = {t: classify_linkedin_tag(t) for t in tags}
        edu = next((t for t, k in kinds.items() if k == "education"), None)
        desc = _s(r.get("job_summary")) if has_text else None
        sen = _s(r.get("job_level"))
        lo, hi = C.seniority_to_exp(sen)
        yield JobRecord(
            source="linkedin", external_id=_ext_id(_s(r.get("job_link")) or f"li-{i}"), title=_s(r.get("job_title")) or "Unknown role",
            company=_s(r.get("company")), location_raw=_s(r.get("job_location")), city=city, cities=[city] if city else [],
            region=region, country=_s(r.get("search_country")), description=desc, skills=tags, seniority=sen, education=edu,
            experience_min=lo, experience_max=hi, experience_source="seniority_map" if lo is not None else None,
            posting_date=C.to_date(r.get("first_seen")), url=_s(r.get("job_link")),
            text_quality="full" if desc else "skills_only", extras={"tag_kinds": kinds, "search_city": _s(r.get("search_city"))})


# =========================================================================== synthetic offline sample / crawled fixture (JSONL)
def load_jsonl(path: Path, source: str, limit: Optional[int] = None) -> Iterator[JobRecord]:
    with open(path, encoding="utf-8") as fh:
        for i, line in enumerate(fh):
            if limit and i >= limit:
                break
            d = json.loads(line)
            d.setdefault("source", source)
            d["source"] = source
            if isinstance(d.get("posting_date"), str):
                d["posting_date"] = C.to_date(d["posting_date"])
            yield JobRecord(**{k: v for k, v in d.items() if k in JobRecord.__dataclass_fields__})
