"""SYNTHETIC user interactions + item-based collaborative filtering.

!! The project has NO real user-behaviour data.  Everything produced by `generate()` is SYNTHETIC: it is flagged is_synthetic everywhere (SyntheticData.label, the users /
!! job_interactions rows written by scripts/generate_synthetic_interactions.py) and must never be reported as evidence about real users.

GENERATIVE MODEL (all assumptions are the parameters of SyntheticConfig, printed with the data):
  persona      one seed job; the persona's skills = a random subset (each kept with prob. persona_keep, at least persona_min) of the seed job's skills; city = the seed job's city.
  affinity     a_uj = cosine(persona skills, job j) in the idf-weighted skill space of the catalogue.
  exposure     the user VIEWS ~Poisson(views_per_user) distinct jobs drawn with probability (1 - uniform_mix) * softmax(a / softmax_temp) + uniform_mix * uniform  (jobs with skills only).
  response     P(click | view) = sigmoid(click_a * (a - click_b));  P(save | click) = save_given_click;  P(apply | click) = apply_given_click.
So the data contain exactly one structure - skill affinity.  Item-based CF recovering it shows that the MACHINERY works; it says nothing about how well CF would work on real behaviour.

ItemKNN: item-item cosine on the implicit user x item matrix (event weights view 1 < click 2 < save 3 < apply 4, the strongest event per pair), shrunk by co-occurrence
c / (c + shrink) so that a similarity backed by one shared user counts little.  A user with no (known) interactions gets NO collaborative score (None) -> the hybrid drops the signal
(cold start) instead of inventing one."""
from __future__ import annotations

from dataclasses import asdict, dataclass, field
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np
import scipy.sparse as sp

EVENT_WEIGHTS = {"view": 1.0, "click": 2.0, "save": 3.0, "apply": 4.0}
LABEL = "SYNTHETIC - generated by jobintel.rec.interactions.generate; not real user behaviour"


@dataclass
class SyntheticConfig:
    n_users: int = 300
    persona_min: int = 3
    persona_keep: float = 0.8
    views_per_user: float = 30.0
    softmax_temp: float = 0.08
    uniform_mix: float = 0.3
    click_a: float = 12.0
    click_b: float = 0.30
    save_given_click: float = 0.25
    apply_given_click: float = 0.15
    seed: int = 42


@dataclass
class SyntheticData:
    config: SyntheticConfig
    personas: List[Dict]                 # per user: {'user': i, 'skills': {...}, 'city': .., 'seed_doc': di}
    user: np.ndarray                     # one row per (user, job) pair
    doc: np.ndarray
    viewed: np.ndarray
    clicked: np.ndarray
    saved: np.ndarray
    applied: np.ndarray
    label: str = LABEL
    is_synthetic: bool = True

    @property
    def n_pairs(self) -> int:
        return len(self.user)

    def weights(self) -> np.ndarray:
        w = np.where(self.viewed, EVENT_WEIGHTS["view"], 0.0)
        for flag, name in ((self.clicked, "click"), (self.saved, "save"), (self.applied, "apply")):
            w = np.where(flag, EVENT_WEIGHTS[name], w)
        return w

    def summary(self) -> Dict:
        return {"label": self.label, "users": len(self.personas), "pairs": int(self.n_pairs), "views": int(self.viewed.sum()), "clicks": int(self.clicked.sum()),
                "saves": int(self.saved.sum()), "applies": int(self.applied.sum()), "config": asdict(self.config)}


def _sigmoid(x):
    return 1.0 / (1.0 + np.exp(-x))


def generate(catalog, cfg: Optional[SyntheticConfig] = None) -> SyntheticData:
    cfg = cfg or SyntheticConfig()
    rng = np.random.default_rng(cfg.seed)
    eligible = np.array([i for i in range(catalog.N) if len(catalog.job_skills(i)) >= cfg.persona_min])
    if not len(eligible):
        raise ValueError("no job has enough skills to seed a persona")
    has = np.where(catalog.has_skills)[0]
    personas, U, D, V, C, S, A = [], [], [], [], [], [], []
    for u in range(cfg.n_users):
        seed_doc = int(rng.choice(eligible))
        sk = catalog.job_skills(seed_doc)
        keep = [s for s in sk if rng.random() < cfg.persona_keep]
        if len(keep) < cfg.persona_min:
            keep = list(rng.choice(sk, size=min(len(sk), cfg.persona_min), replace=False))
        weights = {s: 1.0 for s in keep}
        aff = catalog.content_scores(weights)
        aff = np.zeros(catalog.N) if aff is None else aff
        z = aff[has] / cfg.softmax_temp
        p = np.exp(z - z.max())
        p = (1 - cfg.uniform_mix) * p / p.sum() + cfg.uniform_mix / len(has)
        n_views = int(min(max(1, rng.poisson(cfg.views_per_user)), len(has)))
        docs = rng.choice(has, size=n_views, replace=False, p=p / p.sum())
        a = aff[docs]
        click = rng.random(n_views) < _sigmoid(cfg.click_a * (a - cfg.click_b))
        save = click & (rng.random(n_views) < cfg.save_given_click)
        apply = click & (rng.random(n_views) < cfg.apply_given_click)
        personas.append({"user": u, "skills": weights, "city": catalog.ix.meta["city"][seed_doc], "seed_doc": seed_doc})
        U.append(np.full(n_views, u)); D.append(docs); V.append(np.ones(n_views, bool)); C.append(click); S.append(save); A.append(apply)
    cat = lambda x: np.concatenate(x)
    return SyntheticData(cfg, personas, cat(U), cat(D), cat(V), cat(C), cat(S), cat(A))


class ItemKNN:
    def __init__(self, n_items: int, shrink: float = 10.0, min_item_count: int = 2):
        self.n_items, self.shrink, self.min_item_count = n_items, shrink, min_item_count
        self.S: Optional[sp.csr_matrix] = None
        self.item_count = np.zeros(n_items, dtype=np.int64)
        self.popularity = np.zeros(n_items)

    def fit(self, users: Sequence[int], items: Sequence[int], weights: Sequence[float]) -> "ItemKNN":
        users, items, weights = np.asarray(users), np.asarray(items), np.asarray(weights, dtype=np.float64)
        nu = int(users.max()) + 1 if len(users) else 0
        R = sp.csr_matrix((weights, (users, items)), shape=(nu, self.n_items))
        B = (R > 0).astype(np.float64)
        self.item_count = np.asarray(B.sum(axis=0)).ravel().astype(np.int64)
        self.popularity = np.asarray(R.sum(axis=0)).ravel()
        keep = (self.item_count >= self.min_item_count).astype(np.float64)
        R = R @ sp.diags(keep)
        B = B @ sp.diags(keep)
        norms = np.sqrt(np.asarray(R.multiply(R).sum(axis=0)).ravel())
        Rn = R @ sp.diags(np.where(norms > 0, 1.0 / np.maximum(norms, 1e-12), 0.0))
        S = (Rn.T @ Rn).tocsr()
        C = (B.T @ B).tocsr()
        S.setdiag(0)
        S.eliminate_zeros()
        C = C.multiply(S != 0).tocsr()
        shr = C.copy()
        shr.data = shr.data / (shr.data + self.shrink)
        self.S = S.multiply(shr).tocsr()
        return self

    def score(self, user_items: Dict[int, float]) -> Optional[np.ndarray]:
        """scores for ALL items from one user's interactions {item: weight}; None when none of them is a known item (cold start)."""
        if self.S is None:
            raise RuntimeError("fit first")
        known = {i: w for i, w in user_items.items() if 0 <= i < self.n_items and self.item_count[i] >= self.min_item_count}
        if not known:
            return None
        r = np.zeros(self.n_items)
        for i, w in known.items():
            r[i] = w
        s = np.asarray(self.S @ r).ravel()                  # S is symmetric: score_j = sum_i S[j, i] * r_i
        return s if s.any() else None


def wilson(hits: int, n: int, z: float = 1.96) -> Tuple[float, float]:
    if n == 0:
        return (float("nan"), float("nan"))
    p = hits / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return ((c - h) / d, (c + h) / d)


def evaluate_holdout(data: SyntheticData, catalog, *, k: int = 10, folds: int = 5, seed: int = 0, shrink: float = 10.0, min_hold: int = 4) -> Dict:
    """For each user with >= min_hold interacted jobs hold out ONE strongest-event job (users are split in folds; the model is fitted on everything except the held-out pairs).
    hit@k = the held-out job is in the user's top-k among all jobs not already in their training history; with ONE held-out job per user recall@k = hit rate and precision@k = hits / (k * users);
    coverage = share of the catalogue's jobs that appear in at least one user's top-k list.  References: random (k / candidates), popularity (training event
    weight per job) and 'persona oracle' (content score from the generator's own persona skills - it SEES the latent variable, so it is an upper-ish reference, not a competitor)."""
    rng = np.random.default_rng(seed)
    w_all = data.weights()
    by_user: Dict[int, List[int]] = {}
    for idx, u in enumerate(data.user):
        by_user.setdefault(int(u), []).append(idx)
    users = [u for u, ix in by_user.items() if len(ix) >= min_hold]
    rng.shuffle(users)
    fold_of = {u: i % folds for i, u in enumerate(users)}
    hold: Dict[int, int] = {}
    for u in users:
        ix = by_user[u]
        top = [i for i in ix if w_all[i] == max(w_all[j] for j in ix)]
        hold[u] = int(rng.choice(top))
    N = catalog.N
    res = {"itemknn": [], "popularity": [], "persona_oracle": [], "random_expected": []}
    shown = {"itemknn": set(), "popularity": set(), "persona_oracle": set()}      # distinct jobs shown in any top-k list (catalogue coverage)
    for f in range(folds):
        held = {hold[u] for u in users if fold_of[u] == f}
        mask = np.array([i not in held for i in range(data.n_pairs)])
        model = ItemKNN(N, shrink=shrink).fit(data.user[mask], data.doc[mask], w_all[mask])
        for u in [u for u in users if fold_of[u] == f]:
            hi = hold[u]
            target = int(data.doc[hi])
            history = {int(data.doc[i]): float(w_all[i]) for i in by_user[u] if i != hi}
            cand = np.ones(N, dtype=bool)
            cand[list(history)] = False
            cand &= catalog.has_skills
            if not cand[target]:
                continue
            n_cand = int(cand.sum())

            def run(scores):
                if scores is None:
                    return 0, np.zeros(0, dtype=np.int64)
                sc = np.where(cand, scores, -np.inf)
                better = int((sc > sc[target]).sum())
                top = np.argpartition(-sc, min(k, N - 1))[:k]
                return int(better < k), top[np.isfinite(sc[top])]
            for name, scores in (("itemknn", model.score(history)), ("popularity", model.popularity), ("persona_oracle", catalog.content_scores(data.personas[u]["skills"]))):
                h_, top_ = run(scores)
                res[name].append(h_)
                shown[name].update(int(x) for x in top_)
            res["random_expected"].append(min(1.0, k / n_cand))
    n = len(res["itemknn"])
    out = {"label": LABEL, "k": k, "users_evaluated": n, "folds": folds}
    for name in ("itemknn", "popularity", "persona_oracle"):
        h = int(sum(res[name]))
        lo, hi = wilson(h, n)
        out[name] = {"hit_rate": h / n if n else float("nan"), "ci95": [lo, hi], "hits": h, "precision@k": h / (k * n) if n else float("nan"), "recall@k": h / n if n else float("nan"),
                     "coverage": len(shown[name]) / max(1, int(catalog.has_skills.sum()))}
    out["random_expected"] = float(np.mean(res["random_expected"])) if n else float("nan")
    return out
