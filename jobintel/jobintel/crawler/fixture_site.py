"""Generates a small STATIC job-board website from the synthetic sample jobs so the crawlers have a legal, offline target.

    /index.html                         entry page (also links to a robots-disallowed page, to prove compliance)
    /robots.txt  /sitemap.xml
    /companies/index.html               list of companies
    /companies/<slug>/index.html        company page      -> link to its career page
    /companies/<slug>/careers.html      career page (paginated, 15 jobs/page) -> links to job pages
    /jobs/<id>.html                     job page; odd ids carry JSON-LD, even ids plain CSS-class HTML; 'related jobs' links
    /private/internal.html              Disallowed in robots.txt

The link structure is exactly the graph PageRank needs:  Company -> Career page -> Job -> Related job.
Every page says it is SYNTHETIC."""
from __future__ import annotations

import html
import json
import random
import re
import shutil
import threading
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Dict, List, Optional

PAGE = """<!doctype html><html lang="en"><head><meta charset="utf-8"><title>{title}</title>
<meta name="generator" content="jobintel-fixture (SYNTHETIC)">{head}</head>
<body data-page-type="{ptype}">{body}<footer><small>Synthetic demo site generated by the JobIntel project - not a real employer.</small></footer></body></html>"""


def slugify(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def text_to_html(text: str) -> str:
    out, in_list = [], False
    for line in text.split("\n"):
        line = line.strip()
        if line.startswith("•"):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{html.escape(line.lstrip('• ').strip())}</li>")
            continue
        if in_list:
            out.append("</ul>")
            in_list = False
        if not line:
            continue
        out.append(f"<h3>{html.escape(line[:-1])}</h3>" if line.endswith(":") and len(line) < 40 else f"<p>{html.escape(line)}</p>")
    if in_list:
        out.append("</ul>")
    return "".join(out)


def build_site(out_dir: Path, jobs: List[Dict], n_reposts: int = 6, seed: int = 1, per_page: int = 15) -> Dict:
    out = Path(out_dir)
    if out.exists():
        shutil.rmtree(out)
    for d in ("jobs", "companies", "private"):
        (out / d).mkdir(parents=True)
    rng = random.Random(seed)
    pages = [dict(j, _id=i + 1) for i, j in enumerate(jobs)]
    for k, j in enumerate(rng.sample(pages, min(n_reposts, len(pages)))):         # reposted ads = exact duplicates under new URLs
        pages.append(dict(j, _id=len(jobs) + k + 1, _repost_of=j["_id"]))
    by_company: Dict[str, List[Dict]] = {}
    for p in pages:
        by_company.setdefault(p["company"], []).append(p)
    by_cat: Dict[str, List[Dict]] = {}
    for p in pages:
        by_cat.setdefault(p.get("category") or "x", []).append(p)

    def write(rel: str, content: str) -> None:
        f = out / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding="utf-8")

    for p in pages:
        peers = [q for q in by_cat[p.get("category") or "x"] if q["_id"] != p["_id"] and set(q["skills"]) & set(p["skills"])]
        related = rng.sample(peers, min(3, len(peers))) if peers else []
        slug = slugify(p["company"])
        desc_html = text_to_html(p["description"])
        rel_html = "<ul class='related-jobs'>" + "".join(f"<li><a class='related-link' href='/jobs/{q['_id']}.html'>{html.escape(q['title'])}</a></li>" for q in related) + "</ul>"
        crumbs = f"<a class='company-link' href='/companies/{slug}/index.html'>{html.escape(p['company'])}</a>"
        if p["_id"] % 2:   # JSON-LD template
            ld = {"@context": "https://schema.org/", "@type": "JobPosting", "title": p["title"], "description": desc_html, "datePosted": p["posting_date"],
                  "employmentType": p["employment_type"], "hiringOrganization": {"@type": "Organization", "name": p["company"]},
                  "jobLocation": {"@type": "Place", "address": {"@type": "PostalAddress", "addressLocality": p["city"], "addressCountry": "IN"}},
                  "skills": ", ".join(p["skills"]), "experienceRequirements": p["experience_text"], "educationRequirements": p["education"], "occupationalCategory": p.get("category")}
            head = f'<script type="application/ld+json">{json.dumps(ld)}</script>'
            body = f"<header>{crumbs}</header><main><h1>{html.escape(p['title'])}</h1><div class='job-description'>{desc_html}</div>{rel_html}</main>"
        else:              # plain CSS-class template
            head = ""
            body = (f"<header>{crumbs}</header><main><h1 class='job-title'>{html.escape(p['title'])}</h1><span class='company-name'>{html.escape(p['company'])}</span>"
                    f" <span class='job-location'>{html.escape(p['city'])}</span> <span class='job-experience'>{html.escape(p['experience_text'])}</span>"
                    f" <span class='job-education'>{html.escape(p['education'])}</span> <span class='job-type'>{html.escape(p['employment_type'])}</span>"
                    f" <span class='job-category'>{html.escape(p.get('category') or '')}</span> <time class='posted' datetime='{p['posting_date']}'>{p['posting_date']}</time>"
                    f"<div class='job-description'>{desc_html}</div><ul class='skills'>" + "".join(f"<li>{html.escape(s)}</li>" for s in p["skills"]) + f"</ul>{rel_html}</main>")
        write(f"jobs/{p['_id']}.html", PAGE.format(title=html.escape(p["title"]), head=head, ptype="job", body=body))

    for company, jl in by_company.items():
        slug = slugify(company)
        write(f"companies/{slug}/index.html", PAGE.format(title=company, head="", ptype="company", body=(
            f"<h1>{html.escape(company)}</h1><p class='company-about'>{html.escape(company)} is a fictional employer used for crawler tests.</p>"
            f"<a class='careers-link' href='/companies/{slug}/careers.html'>Careers at {html.escape(company)}</a>")))
        chunks = [jl[i:i + per_page] for i in range(0, len(jl), per_page)]
        for n, chunk in enumerate(chunks, 1):
            name = "careers.html" if n == 1 else f"careers-{n}.html"
            nxt = f"<a class='next-page' href='/companies/{slug}/careers-{n + 1}.html'>Next page</a>" if n < len(chunks) else ""
            lis = "".join(f"<li><a class='job-link' href='/jobs/{q['_id']}.html'>{html.escape(q['title'])}</a> - {html.escape(q['city'])}</li>" for q in chunk)
            write(f"companies/{slug}/{name}", PAGE.format(title=f"Careers - {company}", head="", ptype="careers", body=f"<h1>Careers at {html.escape(company)}</h1><ul>{lis}</ul>{nxt}"))
    write("companies/index.html", PAGE.format(title="Companies", head="", ptype="index", body="<h1>Companies</h1><ul>" + "".join(
        f"<li><a class='company-link' href='/companies/{slugify(c)}/index.html'>{html.escape(c)}</a></li>" for c in sorted(by_company)) + "</ul>"))
    write("index.html", PAGE.format(title="JobIntel fixture careers network", head="", ptype="index", body=(
        "<h1>JobIntel fixture careers network</h1><a href='/companies/index.html'>All companies</a> | <a href='/private/internal.html'>Internal (not for crawlers)</a>")))
    write("private/internal.html", PAGE.format(title="Private", head="", ptype="other", body="<h1>Internal page - robots.txt disallows crawling this.</h1>"))
    write("robots.txt", "User-agent: *\nDisallow: /private/\nCrawl-delay: 0\nSitemap: /sitemap.xml\n")
    write("sitemap.xml", '<?xml version="1.0"?><urlset>' + "".join(f"<url><loc>/jobs/{p['_id']}.html</loc></url>" for p in pages) + "</urlset>")
    return dict(jobs=len(pages), unique_jobs=len(jobs), reposts=len(pages) - len(jobs), companies=len(by_company), out=str(out))


class _QuietHandler(SimpleHTTPRequestHandler):
    log_paths: List[str] = []

    def log_message(self, fmt, *args):      # record requests instead of printing them
        self.server.request_log.append(self.path)


def serve(directory: Path, port: int = 0, host: str = "127.0.0.1") -> tuple[ThreadingHTTPServer, str]:
    """Start the fixture site in a background thread. Returns (server, base_url); call server.shutdown() when done."""
    srv = ThreadingHTTPServer((host, port), partial(_QuietHandler, directory=str(directory)))
    srv.request_log = []
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv, f"http://{host}:{srv.server_address[1]}"
